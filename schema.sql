-- Docker's postgres entrypoint already creates and selects the pawshome database
-- via POSTGRES_DB, so this script only needs to define schema objects.

CREATE TYPE petstatus AS ENUM (
    'active',
    'pending',
    'adopted'
);

CREATE TYPE adoptionstatus AS ENUM (
    'pending',
    'approved',
    'rejected',
    'completed'
);

CREATE TYPE notificationtype AS ENUM (
    'adoption_request',
    'adoption_approved',
    'adoption_completed',
    'general'
);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    email         VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(100),
    created_at    TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE pets (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        INTEGER      NOT NULL,
    name            VARCHAR(100) NOT NULL,
    species         VARCHAR(50)  NOT NULL,
    breed           VARCHAR(100),
    age_years       NUMERIC(4, 1),
    description     TEXT,
    photo_url       VARCHAR(500),
    is_for_adoption BOOLEAN      NOT NULL DEFAULT FALSE,
    status          petstatus    NOT NULL DEFAULT 'active',
    created_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_pet_owner FOREIGN KEY (owner_id)
        REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE adoptions (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id            INTEGER        NOT NULL,
    adopter_id        INTEGER        NOT NULL,
    previous_owner_id INTEGER        NOT NULL,
    status            adoptionstatus NOT NULL DEFAULT 'pending',
    message           TEXT,
    requested_at      TIMESTAMP      NOT NULL DEFAULT NOW(),
    completed_at      TIMESTAMP,
    CONSTRAINT fk_adoption_pet FOREIGN KEY (pet_id)
        REFERENCES pets(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_adoption_adopter FOREIGN KEY (adopter_id)
        REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_adoption_prev_owner FOREIGN KEY (previous_owner_id)
        REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE notifications (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER          NOT NULL,
    title          VARCHAR(255)     NOT NULL,
    message        TEXT             NOT NULL,
    type           notificationtype NOT NULL DEFAULT 'general',
    is_read        BOOLEAN          NOT NULL DEFAULT FALSE,
    related_pet_id INTEGER,
    created_at     TIMESTAMP        NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_notif_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_notif_pet FOREIGN KEY (related_pet_id)
        REFERENCES pets(id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_pets_updated_at
BEFORE UPDATE ON pets
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE INDEX idx_pets_owner ON pets (owner_id);
CREATE INDEX idx_pets_adoption ON pets (is_for_adoption, status);
CREATE INDEX idx_adoptions_pet ON adoptions (pet_id, status);
CREATE INDEX idx_adoptions_adopter ON adoptions (adopter_id);
CREATE INDEX idx_notif_user_unread ON notifications (user_id, is_read);
